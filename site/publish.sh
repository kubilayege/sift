#!/bin/sh
# Publish a sift release and the site:
#   1. upload ../release/*.tar.gz (from ../scripts/release.sh) as a GitHub release on $REPO,
#      since Lakebed storage does not accept executables;
#   2. regenerate shared/releases.ts with the asset URLs, sizes and checksums;
#   3. deploy the capsule, so the page, /install.sh and /download/* point at the new release.
set -e
cd "$(dirname "$0")"
REPO=kubilayege/sift
# Personal account; the gh CLI may have several logged in.
export GH_TOKEN="${GH_TOKEN:-$(gh auth token --user kubilayege)}"
REL=../release
[ -f "$REL/VERSION" ] || { echo "publish: run ../scripts/release.sh first" >&2; exit 1; }
VERSION=$(cat "$REL/VERSION")
TAG="v$VERSION"

if gh release view "$TAG" --repo "$REPO" >/dev/null 2>&1; then
  gh release upload "$TAG" "$REL"/sift-*.tar.gz "$REL/SHA256SUMS" --repo "$REPO" --clobber
else
  gh release create "$TAG" "$REL"/sift-*.tar.gz "$REL/SHA256SUMS" --repo "$REPO" \
    --title "sift $VERSION" --notes "Install: \`curl -fsSL https://sift.lakebed.app/install.sh | sh\` · https://sift.lakebed.app"
fi

tmp=shared/releases.ts.tmp
{
  echo "// Generated by publish.sh from ../release. Do not edit by hand."
  echo 'import type { Release } from "./types";'
  echo
  echo "export const VERSION = \"$VERSION\";"
  echo
  echo "export const RELEASES: Release[] = ["
  for f in "$REL"/sift-*.tar.gz; do
    name=$(basename "$f" .tar.gz)
    sha=$(shasum -a 256 "$f" | cut -d' ' -f1)
    size=$(wc -c < "$f" | tr -d ' ')
    echo "  { name: \"$name\", url: \"https://github.com/$REPO/releases/download/$TAG/$name.tar.gz\", sha256: \"$sha\", size: $size },"
  done
  echo "];"
} > "$tmp"
mv "$tmp" shared/releases.ts
npx lakebed deploy
